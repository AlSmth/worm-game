/** Рост червя: тиры размера T1…T21 (концепт, раздел 5). Все числа здесь, чтобы балансировать без правки кода. */

import { SKY_TIER, SURFACE_TIER } from './world';

export const MAX_TIER = 21;

/**
 * Масштаб червя по тирам T1…T21 (1 — мир почвы). Мир устроен в реальных пропорциях: жук ≪ человек ≪ машина ≪ дом ≪ небоскрёб,
 * а достигается это тем, что червь растёт, а камера отъезжает (вид растёт как масштаб в степени 0,85, см. GameScene).
 * Размеры добычи абсолютные (px мира, человек ростом 1500 px); съедобно то, что помещается в пасть (радиус 60 × масштаб).
 * T5 даёт пасть 750 px, достаточную для человека; T12 пасть 18 600 px, достаточную для небоскрёба.
 * Небо (T13-T16): пасть 25 000, 40 000, 55 000, 75 000 (самолёты, вертолёты, лайнеры, грузовые гиганты). Космос (T17-T21): пасть
 * 200 000 (спутники, станции), 800 000, 3 000 000 (астероиды), 12 000 000 (Луна), 40 000 000 (Земля).
 */
const SCALES = [1, 1.9, 3.6, 6.8, 12.5, 20, 33, 52, 70, 83, 115, 310, 417, 667, 917, 1250, 3333, 13300, 50000, 200000, 670000];

/**
 * Во сколько раз вид (px мира на экран) больше, чем при масштабе червя 1: до 12-го тира вид растёт как масштаб в степени 0,85 (голова
 * червя на экране плавно крупнеет с 48 до 113 px), дальше как сам масштаб (голова остаётся ≈ 115 px, червь вровень с планетой).
 */
export const VIEW_BREAK = 310;
export function viewScale(S: number): number {
  return S <= VIEW_BREAK ? Math.pow(S, 0.85) : Math.pow(VIEW_BREAK, 0.85) * (S / VIEW_BREAK);
}

/** Масштаб червя на (дробном) тире t ≥ 1: между тирами плавно (по степенному закону). */
export function wormScale(t: number): number {
  const c = Math.max(1, Math.min(SCALES.length, t));
  const i = Math.min(SCALES.length - 2, Math.floor(c) - 1);
  return SCALES[i] * Math.pow(SCALES[i + 1] / SCALES[i], c - 1 - i);
}

/** Рост «экономики» с тиром (ценность сокровищ и награды испытаний): ×1,14 за тир, цены улучшений рассчитаны на это. */
export function econScale(tier: number): number {
  return Math.pow(1.14, tier - 1);
}

/** Число сегментов тела на (дробном) тире t. */
export function segmentsAt(t: number): number {
  return 5 + 1.5 * (t - 1);
}

/**
 * Сколько очков роста нужно, чтобы пройти тир. Темп зоны 1 (решение автора): поверхность открывается не позже чем
 * через 2 минуты живой игры, автопилот проходит T1-T5 примерно за минуту.
 */
export function growthNeeded(tier: number): number {
  if (tier >= SKY_TIER) {
    // небо и космос: быстрее зоны 2, около минуты на тир автопилоту (концепт, раздел 3: ≈ 16 % игры на зону)
    const i = tier - SKY_TIER;
    return i < AIR_NEED.length ? AIR_NEED[i] : AIR_NEED[AIR_NEED.length - 1];
  }
  if (tier >= SURFACE_TIER) {
    // зона 2 «Поверхность» (самая длинная, концепт, раздел 3): по 2-3 минуты на тир
    const i = tier - SURFACE_TIER;
    return i < ZONE2_NEED.length ? ZONE2_NEED[i] : Math.round(ZONE2_NEED[ZONE2_NEED.length - 1] * Math.pow(1.15, i - ZONE2_NEED.length + 1));
  }
  return Math.round(55 * Math.pow(1.12, tier - 1));
}

/** Очков роста на тиры 13-21 (небо T13-T16, космос T17-T21). Очки за добычу лежат в src/data/air.ts. */
const AIR_NEED = [1800, 2500, 3400, 4500, 2900, 4800, 13500, 21000, 9000];

/** Очков роста на тиры 5-12 (зона 2). Очки за добычу лежат в src/data/surface.ts: человек 1, машина 5, дом 8 и так далее. */
const ZONE2_NEED = [70, 100, 260, 480, 620, 780, 1040, 1400];

/** Очки роста за подземную добычу с радиусом r (абсолютные px мира): чем крупнее жук, тем больше очков, от размера червя не зависит. */
export function growthFor(radius: number): number {
  return Math.pow(radius, 1.6) / 100;
}
